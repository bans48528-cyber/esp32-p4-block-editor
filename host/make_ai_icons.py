"""Export the supplied Illustrator artboards as transparent LVGL icon assets.

Requires PyMuPDF and Pillow. The original .ai is opened read-only. SVGs retain
the artboard's colours, paths and 500x500 alignment; only the background tile,
off-artboard labels and unused font definitions are removed.
"""
from pathlib import Path
import argparse
import hashlib
import io
import json
import xml.etree.ElementTree as ET

import pymupdf
from PIL import Image

NAMES = [
    "motor-forward", "motor-reverse", "motor-forward-continuous",
    "motor-reverse-continuous", "motor-stop", "motor-power",
    "combo-forward", "combo-backward", "combo-turn-right", "combo-turn-left",
    "combo-forward-continuous", "combo-backward-continuous", "wait-time",
    "loop", "combo-turn-right-continuous", "combo-turn-left-continuous",
    "combo-stop", "combo-power", "ultrasonic-sensor", "button-sensor",
    "grayscale-sensor", "host-button", "start", "combo-direction", "play-note",
]
# Existing serialized type IDs stay unchanged. MATRIX is rendered from its data.
TYPE_PAGES = [23, 1, 13, 14, 2, 5, 7, 8, 10, 9, 17, 19, 21, 20, 22,
              14, 25, None, 6, 3, 4, 18, 11, 24]
COMBO_CONTINUOUS_PAGES = [11, 12, 16, 15]  # forward, backward, left, right


def export_ai(source, destination):
    doc = pymupdf.open(source)
    if len(doc) != len(NAMES):
        raise ValueError(f"Expected 25 artboards, got {len(doc)}")
    destination.mkdir(parents=True, exist_ok=True)
    manifest = {"source": source.name,
                "source_sha256": hashlib.sha256(source.read_bytes()).hexdigest(),
                "size": 52, "artboards": []}
    ns = "{http://www.w3.org/2000/svg}"
    for index, page in enumerate(doc):
        root = ET.fromstring(page.get_svg_image())
        label = "".join(e.get("data-text", "") for e in root.iter(ns + "use"))
        layer = next(e for e in root if e.tag == ns + "g")
        background = next(e for e in layer if e.tag == ns + "path")
        bounds = page.get_drawings()[0]["rect"]
        if any(abs(a-b) > .01 for a,b in zip(bounds, (0, 0, 500, 500))):
            raise ValueError(f"Unexpected artboard background: {index + 1}")
        background_colour = background.get("fill")
        layer.remove(background)
        for parent in root.iter():
            for child in list(parent):
                if child.tag == ns + "use" or child.get("id", "").startswith("font_"):
                    parent.remove(child)
        name = NAMES[index]
        (destination / f"{name}.svg").write_text(ET.tostring(root, encoding="unicode"), encoding="utf-8")
        manifest["artboards"].append({"page": index + 1, "name": name,
                                     "label": label, "background": background_colour})
    (destination / "manifest.json").write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def generate(root):
    assets = root / "assets/block-icons"
    images = []
    code = ["/* Generated by host/make_ai_icons.py from the SVG exports in assets/block-icons. */",
            '#include "projects.h"', '#include "lvgl.h"', ""]
    for number, name in enumerate(NAMES, 1):
        with pymupdf.open(assets / f"{name}.svg") as svg:
            pix = svg[0].get_pixmap(matrix=pymupdf.Matrix(.416, .416), alpha=True)
            # PNG export unpremultiplies MuPDF's alpha before downsampling.
            image = Image.open(io.BytesIO(pix.tobytes("png"))).convert("RGBA")
        image = image.resize((52, 52), Image.Resampling.LANCZOS)
        if image.getpixel((0, 0))[3] or not image.getbbox():
            raise ValueError(f"Invalid transparent icon: {name}")
        images.append(image)
        data = image.tobytes("raw", "BGRA")
        code.append(f"/* Artboard {number}: {name} */")
        code.append(f"static const uint8_t pixels_{number}[] = {{")
        code.extend("  " + ",".join(str(v) for v in data[i:i + 32]) + "," for i in range(0, len(data), 32))
        code.append("};")
        code.append(f"static const lv_image_dsc_t image_{number} = {{.header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_ARGB8888, .w = 52, .h = 52, .stride = 208}}, .data_size = sizeof(pixels_{number}), .data = pixels_{number}}};")
    code.append("const lv_image_dsc_t *const block_icons[TYPES + 1] = {")
    code.extend("  " + (f"&image_{p}," if p else "NULL, /* dynamic point matrix */") for p in TYPE_PAGES)
    code.append("};")
    code.append("const lv_image_dsc_t *const combo_continuous_icons[4] = {" + ",".join(f"&image_{p}" for p in COMBO_CONTINUOUS_PAGES) + "};")
    (root / "main").mkdir(exist_ok=True)
    (root / "main/block_icons.c").write_text("\n".join(code) + "\n", encoding="utf-8")
    print(f"Generated {len(images)} icons, {len(images)*52*52*4} bytes in read-only image data")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--source-ai", type=Path, help="Re-export artboards; omit to use the checked-in SVGs")
    args = parser.parse_args()
    if args.source_ai:
        export_ai(args.source_ai, args.root / "assets/block-icons")
    generate(args.root)
